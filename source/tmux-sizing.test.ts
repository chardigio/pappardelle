// ============================================================================
// ASCII Art Viewport Rendering
// ============================================================================

/**
 * Render a full viewport ASCII representation of a horizontal layout.
 * Each character represents one cell. Pipes (|) represent tmux borders.
 *
 * Example for 30x5 with list=8, agent=12, companion=8:
 * LLLLLLLL|CCCCCCCCCCCC|GGGGGGGG
 * LLLLLLLL|CCCCCCCCCCCC|GGGGGGGG
 * LLLLLLLL|CCCCCCCCCCCC|GGGGGGGG
 * LLLLLLLL|CCCCCCCCCCCC|GGGGGGGG
 * LLLLLLLL|CCCCCCCCCCCC|GGGGGGGG
 */
function renderHorizontalViewport(
	listWidth: number,
	agentWidth: number,
	companionWidth: number,
	height: number,
): string {
	const row =
		'L'.repeat(listWidth) +
		'|' +
		'C'.repeat(agentWidth) +
		'|' +
		'G'.repeat(companionWidth);
	const rows: string[] = [];
	for (let i = 0; i < height; i++) {
		rows.push(row);
	}
	return rows.join('\n');
}

/**
 * Render a full viewport ASCII representation of a vertical layout.
 * List pane on top, border row, Claude pane below.
 *
 * Example for 40x10 with listHeight=4, agentHeight=5:
 * LLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLL
 * LLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLL
 * LLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLL
 * LLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLLL
 * ────────────────────────────────────────
 * CCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCC
 * CCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCC
 * CCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCC
 * CCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCC
 * CCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCCC
 */
function renderVerticalViewport(
	width: number,
	listHeight: number,
	agentHeight: number,
): string {
	const listRow = 'L'.repeat(width);
	const border = '─'.repeat(width);
	const claudeRow = 'C'.repeat(width);

	const rows: string[] = [];
	for (let i = 0; i < listHeight; i++) {
		rows.push(listRow);
	}
	rows.push(border);
	for (let i = 0; i < agentHeight; i++) {
		rows.push(claudeRow);
	}

	return rows.join('\n');
}

/**
 * Parse a horizontal viewport ASCII into dimensions.
 */
function parseHorizontalViewport(ascii: string): {
	listWidth: number;
	agentWidth: number;
	companionWidth: number;
	height: number;
} {
	const lines = ascii.trim().split('\n');
	const firstLine = lines[0]!;
	const parts = firstLine.split('|');

	if (parts.length !== 3) {
		throw new Error(`Expected 3 panes separated by |, got ${parts.length}`);
	}

	return {
		listWidth: parts[0]!.length,
		agentWidth: parts[1]!.length,
		companionWidth: parts[2]!.length,
		height: lines.length,
	};
}

/**
 * Parse a vertical viewport ASCII into dimensions.
 */
function parseVerticalViewport(ascii: string): {
	width: number;
	listHeight: number;
	agentHeight: number;
} {
	const lines = ascii.trim().split('\n');

	// Find the border row (all ─ characters)
	const borderIndex = lines.findIndex(line => /^─+$/.test(line));
	if (borderIndex === -1) {
		throw new Error('No border row found in vertical layout');
	}

	const width = lines[0]!.length;
	const listHeight = borderIndex;
	const agentHeight = lines.length - borderIndex - 1;

	return {width, listHeight, agentHeight};
}

/**
 * Assert that a calculated layout matches the expected ASCII viewport.
 */
function assertViewport(
	layout: LayoutConfig,
	expectedAscii: string,
	label: string,
) {
	const trimmedExpected = expectedAscii.trim();

	if (layout.direction === 'horizontal') {
		const expected = parseHorizontalViewport(trimmedExpected);
		const actual = renderHorizontalViewport(
			layout.listWidth!,
			layout.agentWidth!,
			layout.companionWidth!,
			expected.height,
		);

		if (actual !== trimmedExpected) {
			console.log(`\n${label} - MISMATCH`);
			console.log('Expected:');
			console.log(trimmedExpected);
			console.log('\nActual:');
			console.log(actual);
			console.log(
				`\nDimensions: list=${layout.listWidth}, agent=${layout.agentWidth}, companion=${layout.companionWidth}`,
			);
		}

		expect(layout.listWidth, `${label}: list width`).toBe(expected.listWidth);
		expect(layout.agentWidth, `${label}: claude width`).toBe(
			expected.agentWidth,
		);
		expect(layout.companionWidth, `${label}: companion width`).toBe(
			expected.companionWidth,
		);
	} else {
		const expected = parseVerticalViewport(trimmedExpected);
		const actual = renderVerticalViewport(
			expected.width,
			layout.listHeight!,
			layout.agentHeight!,
		);

		if (actual !== trimmedExpected) {
			console.log(`\n${label} - MISMATCH`);
			console.log('Expected:');
			console.log(trimmedExpected);
			console.log('\nActual:');
			console.log(actual);
			console.log(
				`\nDimensions: listHeight=${layout.listHeight}, agentHeight=${layout.agentHeight}`,
			);
		}

		expect(layout.listHeight, `${label}: list height`).toBe(
			expected.listHeight,
		);
		expect(layout.agentHeight, `${label}: claude height`).toBe(
			expected.agentHeight,
		);
	}
}

